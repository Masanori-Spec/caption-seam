test('BOM, CRLF, nonconsecutive numbering and actual UTF-8 survive parsing', () => {
  const srt = '\ufeff' + source.replaceAll('\n','\r\n');
  const cues = parseSrt(srt);
  assert.equal(cues.length,6);
  assert.equal(cues.at(-1).text,'Last\ncaption');
  assert.equal(decodeUtf8(new TextEncoder().encode('日本語 🪡')),'日本語 🪡');
  assert.throws(() => decodeUtf8(Uint8Array.from([0xc3,0x28])),codeIs('INVALID_UTF8'));
});

test('cut-map schema is strict about type, ordering, intervals and unsupported edit semantics', () => {
  const invalid = [null,[],{}, {version:2,keep:[{startMs:0,endMs:1000}]},
    {version:1,keep:[]}, {version:1,keep:[{startMs:0,endMs:1000,speed:2}]},
    {version:1,keep:[{startMs:0,endMs:1000}],tracks:[]},
    ...[[[0,0]],[[2,1]],[[-1,2]],[[0,1.5]],[[false,1000]],[[0,NaN]],[[0,Infinity]],
      [[0,'1000']],[[0,Number.MAX_SAFE_INTEGER]],[[0,86400001]],[[0,2000],[1000,3000]],[[2000,3000],[0,1000]]].map(mapOf),
  ];
  for (const bad of invalid) assert.throws(() => parseCutMap(bad),undefined,JSON.stringify(bad));
  assert.throws(() => parseCutMap('{bad json'),codeIs('INVALID_CUT_MAP_JSON'));
  assert.deepEqual(parseCutMap(JSON.stringify(map)),map);
});

test('CSV escapes formula-like source text; provenance preserves the removed fragments', async () => {
  const plan = await analyze(one(0,1000,'=SUM(1,2)') + '\n' + one(5000,8000,'@removed').replace(/^7\n/,'14\n'),map);
  const bundle = exportBundle(plan,emptyDecisions(plan));
  assert.match(bundle.csv,/"'=SUM\(1,2\)"/);
  assert.match(bundle.csv,/"'@removed"/);
  const provenance = JSON.parse(bundle.provenance);
  assert.equal(provenance.sourceHash,plan.sourceHash);
  assert.deepEqual(provenance.cutMap,map);
  assert.equal(provenance.review[1].status,'removed');
  assert.deepEqual(provenance.review[1].outputNumbers,[]);
});

test('export and JSON round-trip do not mutate source plans or review decisions', async () => {
  const {plan,decisions} = await fresh();
  const before = JSON.stringify({plan,decisions});
  const first = exportBundle(plan,decisions);
  const second = exportBundle(plan,JSON.parse(first.decisions));
  assert.equal(first.srt,second.srt);
  assert.equal(first.provenance,second.provenance);
  assert.equal(JSON.stringify({plan,decisions}),before);
});
