/** Adversarial contracts independent of the app's own example fixtures. */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {analyze, decodeUtf8, emptyDecisions, exportBundle, parseCutMap, parseSrt,
  resolve, validateDecisions, validateText} from '../src/core.mjs';

const fixture = JSON.parse(fs.readFileSync(new URL('./fixtures/hand_expected.json', import.meta.url)));
const mapOf = keep => ({version: 1, keep: keep.map(([startMs,endMs]) => ({startMs,endMs}))});
const map = mapOf(fixture.keep);
const clock = ms => `${String(Math.floor(ms / 3600000)).padStart(2,'0')}:${String(Math.floor(ms / 60000) % 60).padStart(2,'0')}:${String(Math.floor(ms / 1000) % 60).padStart(2,'0')},${String(ms % 1000).padStart(3,'0')}`;
const sourceOf = cues => cues.map((c,i) => `${7 + i * 7}\n${clock(c.startMs)} --> ${clock(c.endMs)}\n${c.text}\n`).join('\n');
const source = sourceOf(fixture.source);
const one = (start, end, text = 'Text') => sourceOf([{startMs:start,endMs:end,text}]);
const codeIs = code => error => error?.code === code;
const fresh = async () => {
  const plan = await analyze(source, map);
  const decisions = emptyDecisions(plan);
  decisions.decisions[plan.rows[1].id] = {action:'split',texts:['Before','and after']};
  decisions.decisions[plan.rows[3].id] = {action:'remove'};
  return {plan,decisions};
};

// Exactly known numbers, rather than an output snapshot generated by core.mjs.
test('hand-calculated export has six newly numbered, nonoverlapping cues and exact multiline text', async () => {
  const {plan,decisions} = await fresh();
  const bundle = exportBundle(plan,decisions);
  assert.equal(plan.durationMs,14000);
  assert.deepEqual(bundle.result.cues.map(({number,startMs,endMs,text}) => ({number,startMs,endMs,text})), fixture.output);
  assert.equal(bundle.srt.replace(/\n+$/,''),fixture.srt.replace(/\n+$/,''));
  assert.deepEqual(parseSrt(bundle.srt).map(c => c.sourceNumber),[1,2,3,4,5,6]);
  assert.deepEqual(plan.rows.map(c => c.sourceNumber),[7,14,21,28,35,42]);
  assert.equal(bundle.result.cues.at(-1).text,'Last\ncaption');
  assert.equal(bundle.result.receipt.length,6);
  const removed = bundle.result.receipt[3];
  assert.equal(removed.originalText,'Across a tiny seam');
  assert.deepEqual(removed.outputNumbers,[]);
  assert.deepEqual(removed.decision,{action:'remove'});
});

test('unreviewed cut and tiny fragments block export instead of inferring words', async () => {
  const {plan} = await fresh();
  const decisions = emptyDecisions(plan);
  assert.deepEqual(resolve(plan,decisions).unresolved,[plan.rows[1].id,plan.rows[3].id]);
  assert.throws(() => exportBundle(plan,decisions),codeIs('UNRESOLVED_CUES'));
  decisions.decisions[plan.rows[1].id] = {action:'split',texts:['Before','and after']};
  assert.throws(() => exportBundle(plan,decisions),codeIs('UNRESOLVED_CUES'));
  assert.deepEqual(plan.rows[3].reasons,['clipped','split','short']);
});

test('explicit fragment and continuous decisions produce their exact chosen text', async () => {
  const {plan,decisions} = await fresh();
  decisions.decisions[plan.rows[1].id] = {action:'fragment',fragmentIndex:1,text:'Explicit later words'};
  let cues = exportBundle(plan,decisions).result.cues;
  assert.deepEqual([cues[1].startMs,cues[1].endMs,cues[1].text],[5000,6000,'Explicit later words']);
  decisions.decisions[plan.rows[1].id] = {action:'continuous',text:'Explicit continuity & seam'};
  const bundle = exportBundle(plan,decisions);
  cues = bundle.result.cues;
  assert.deepEqual([cues[1].startMs,cues[1].endMs,cues[1].text],[4000,6000,'Explicit continuity & seam']);
  assert.equal(cues[1].sourceIntervals.length,2);
  assert.match(bundle.vtt,/Explicit continuity &amp; seam/);
});

test('wholly removed sources have receipts but cannot create an empty SRT export', async () => {
  const plan = await analyze(one(5000,8000),map);
  const decisions = emptyDecisions(plan);
  const resolved = resolve(plan,decisions);
  assert.equal(plan.rows[0].status,'removed');
  assert.deepEqual(resolved.cues,[]);
  assert.deepEqual(resolved.unresolved,[]);
  assert.equal(resolved.receipt[0].originalText,'Text');
  assert.deepEqual(resolved.receipt[0].outputNumbers,[]);
  assert.throws(() => exportBundle(plan,decisions),codeIs('EMPTY_EXPORT'));
});

test('499ms requires a decision; 500ms is retained automatically', async () => {
  for (const [length,status] of [[1,'review'],[499,'review'],[500,'automatic'],[501,'automatic']]) {
    const plan = await analyze(one(0,length),mapOf([[0,1000]]));
    assert.equal(plan.rows[0].status,status);
    const decisions = emptyDecisions(plan);
    if (status === 'review') {
      assert.throws(() => exportBundle(plan,decisions),codeIs('UNRESOLVED_CUES'));
      decisions.decisions[plan.rows[0].id] = {action:'fragment',fragmentIndex:0,text:'Explicit short cue'};
    }
    assert.equal(exportBundle(plan,decisions).result.cues[0].endMs,length);
  }
});

test('touching ranges coalesce but zero-duration boundary intersections are discarded', async () => {
  const spanning = await analyze(one(1000,9000),mapOf([[0,5000],[5000,10000]]));
  assert.equal(spanning.rows[0].status,'automatic');
  assert.equal(spanning.rows[0].fragments.length,1);
  assert.deepEqual(spanning.rows[0].fragments[0].rangeIndexes,[0,1]);
  const plan = await analyze(one(4999,8001),map);
  assert.deepEqual(plan.rows[0].fragments.map(f => [f.sourceStartMs,f.sourceEndMs,f.outputStartMs,f.outputEndMs]),
    [[4999,5000,4999,5000],[8000,8001,5000,5001]]);
  for (const [start,end] of [[5000,8000],[12000,15000],[20000,21000]]) {
    const removed = await analyze(one(start,end),map);
    assert.equal(removed.rows[0].status,'removed');
  }
});

