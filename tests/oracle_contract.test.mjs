test('unknown, removed and automatic decision targets are rejected', async () => {
  const {plan,decisions} = await fresh();
  for (const id of ['not-a-source-cue',plan.rows[0].id]) {
    const bundle = structuredClone(decisions);
    bundle.decisions[id] = {action:'remove'};
    assert.throws(() => validateDecisions(plan,bundle),codeIs('DECISION_TARGET_INVALID'));
  }
  const removed = await analyze(one(5000,8000),map);
  const bundle = emptyDecisions(removed);
  bundle.decisions[removed.rows[0].id] = {action:'remove'};
  assert.throws(() => validateDecisions(removed,bundle),codeIs('DECISION_TARGET_INVALID'));
});

test('malformed review actions and missing independently written fragment text are rejected', async () => {
  const {plan,decisions} = await fresh();
  const invalid = [
    {}, {action:'guess'}, {action:'remove',text:'not allowed'},
    {action:'fragment',fragmentIndex:-1,text:'words'}, {action:'fragment',fragmentIndex:2,text:'words'},
    {action:'fragment',fragmentIndex:0.5,text:'words'}, {action:'fragment',fragmentIndex:'0',text:'words'},
    {action:'fragment',fragmentIndex:0}, {action:'fragment',fragmentIndex:0,text:'words',texts:[]},
    {action:'split',texts:['one']}, {action:'split',texts:['one','two','three']},
    {action:'split',texts:['one','']}, {action:'split',texts:['one','two'],text:'ambiguous'},
    {action:'continuous'}, {action:'continuous',text:'words',fragmentIndex:0},
    {action:'continuous',text:'words',extra:'unknown'},
  ];
  for (const decision of invalid) {
    const bundle = structuredClone(decisions);
    bundle.decisions[plan.rows[1].id] = decision;
    assert.throws(() => exportBundle(plan,bundle),undefined,JSON.stringify(decision));
  }
  const clipped = await analyze(one(4000,6000),map);
  for (const decision of [{action:'split',texts:['one']},{action:'continuous',text:'words'}]) {
    const bundle = emptyDecisions(clipped);
    bundle.decisions[clipped.rows[0].id] = decision;
    assert.throws(() => exportBundle(clipped,bundle));
  }
});

test('blank lines introduced by CR normalization cannot escape text validation', () => {
  for (const text of ['one\r\rtwo','one\r \rtwo','one\r\n\r\ntwo','one\n\ntwo']) {
    assert.throws(() => validateText(text),codeIs('PLAIN_TEXT_REQUIRED'),JSON.stringify(text));
  }
  assert.equal(validateText('one\r\ntwo'),'one\ntwo');
});

